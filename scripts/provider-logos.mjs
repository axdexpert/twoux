const LICENCE = { logos: "CC0-1.0", "vscode-icons": "MIT", "thesvg-color": "MIT" };

const bySet = {};
for (const [, , ref] of PROVIDERS) { const [set, icon] = ref.split(":"); (bySet[set] ??= []).push(icon); }
const data = {};
for (const [set, icons] of Object.entries(bySet)) {
	const res = await fetch(`https://api.iconify.design/${set}.json?icons=${icons.join(",")}`);
	const json = await res.json();
	for (const icon of icons) {
		const i = json.icons?.[icon];
		if (!i) throw new Error(`Missing ${set}:${icon}`);
		data[`${set}:${icon}`] = { body: i.body, w: i.width ?? json.width ?? 16, h: i.height ?? json.height ?? 16, left: i.left ?? 0, top: i.top ?? 0 };
	}
}

const out = `// Generated by scripts/provider-logos.mjs. Do not edit: change the list there and re-run.
// twoux-check-disable raw-colour: official brand marks, used unaltered to identify each service.
export type ProviderId = ${PROVIDERS.map(([id]) => JSON.stringify(id)).join(" | ")}

export const PROVIDERS: Record<ProviderId, { label: string; viewBox: string; body: string; source: string }> = {
${PROVIDERS.map(([id, label, ref]) => {
	const d = data[ref];
	const set = ref.split(":")[0];
	return `  ${JSON.stringify(id)}: { label: ${JSON.stringify(label)}, viewBox: "${d.left} ${d.top} ${d.w} ${d.h}", source: "${ref} (${LICENCE[set]})", body: ${JSON.stringify(d.body)} },`;
}).join("\n")}
}
`;
writeFileSync(new URL("../packages/ui/src/components/provider-logos.data.ts", import.meta.url), out);
console.log(`Wrote ${PROVIDERS.length} provider marks.`);
