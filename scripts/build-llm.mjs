// Generates the files AI coding agents read, from the same sources as the docs site.
// Run: pnpm llm   (never edit the outputs by hand)
// Outputs: AGENTS.md, llms.txt, llms-full.txt, docs-md/<id>.md
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const contentDir = join(root, "apps/docs/src/content");
const files = ["foundation", "actions", "feedback", "data", "workspace", "ai", "patterns"];
const ALIAS = { menu: "dropdown-menu", "data-table": "data-grid", filters: "filter-bar", dialog: "confirmation-dialog", "chart-colours": "data-vis-colours" };
const docs = files
	.flatMap((f) => JSON.parse(readFileSync(join(contentDir, `${f}.json`), "utf8")).components)
	.filter((d) => d.id !== "chart-colours")
	.map((d) => ({ ...d, kind: d.kind ?? "component" }));
const byId = Object.fromEntries(docs.map((d) => [d.id, d]));
const rules = JSON.parse(readFileSync(join(root, "packages/ui/registry/rules.json"), "utf8"));
const jobs = JSON.parse(readFileSync(join(root, "packages/ui/registry/jobs.json"), "utf8")).jobs;
const built = new Set(
	readdirSync(join(root, "apps/docs/src/examples")).filter((d) => readdirSync(join(root, "apps/docs/src/examples", d)).some((f) => f.endsWith(".tsx") && f !== "thumbnail.tsx")),
);
const name = (id) => byId[ALIAS[id] ?? id]?.name ?? id;

const path = (d) => `docs-md/${d.id}.md`;

function md(d) {
	const refs = Object.fromEntries(d.references.map((r, i) => [r.id, i + 1]));
	const cite = (s = []) => (s.length ? ` [${s.map((x) => refs[x]).filter(Boolean).join(", ")}]` : "");
	const list = (title, items) => (items?.length ? `\n## ${title}\n\n${items.map((b) => `- ${b.t}${cite(b.s)}`).join("\n")}\n` : "");
	let out = `# ${d.name}\n\n${d.summary}\n\nKind: ${d.kind} · Group: ${d.group}${d.kind === "component" ? ` · Status: ${built.has(d.id) ? "built, import from @twoux/ui" : "planned, guidance only. Do not build a local version; ask for it to be added to @twoux/ui"}` : ""}\n`;
	if (d.problem) out += `\n**Problem:** ${d.problem}\n\n**Solution:** ${d.solution}\n`;
	if (d.components?.length) out += `\n**Built from:** ${d.components.map(name).join(", ")}\n`;
	if (d.steps?.length) out += `\n## How it works\n\n${d.steps.map((s, i) => `${i + 1}. ${s.t}${cite(s.s)}`).join("\n")}\n`;
	out += list("Principles", d.principles);
	out += list("When to use", d.whenToUse);
	out += list("When not to use", d.whenNotToUse);
	if (d.structure?.length) out += `\n## Structure\n\n${d.structure.map((s, i) => `${i + 1}. ${s}`).join("\n")}\n`;
	out += list("Guidelines", d.guidelines);
	out += list("Content", d.content);
	out += list("Accessibility", d.accessibility);
	out += list("Do", d.dos);
	out += list("Don't", d.donts);
	if (d.keyboard?.length) out += `\n## Keyboard\n\n| Keys | Action |\n|---|---|\n${d.keyboard.map((k) => `| ${k.keys} | ${k.action} |`).join("\n")}\n`;
	if (d.tokens?.length) out += `\n## Tokens\n\n| Token | Value | Use |\n|---|---|---|\n${d.tokens.map((t) => `| \`${t.name}\` | \`${t.value}\` | ${t.use} |`).join("\n")}\n`;
	if (d.decisions?.length) out += `\n## TwoUX decisions\n\n${d.decisions.map((x) => `- **${x.decision.replace(/\.?$/, ".")}** ${x.why}${cite(x.s)}`).join("\n")}\n`;
	const ex = join(root, "apps/docs/src/examples", d.id);
	if (existsSync(ex)) {
		const exFiles = readdirSync(ex).filter((f) => f.endsWith(".tsx") && f !== "thumbnail.tsx");
		out += `\n## Examples\n\n${exFiles.map((f) => `### ${f.replace(".tsx", "")}\n\n\`\`\`tsx\n${readFileSync(join(ex, f), "utf8").trim()}\n\`\`\``).join("\n\n")}\n`;
	}
	if (d.related?.length) out += `\n## Related\n\n${d.related.map((r) => `- ${name(r)}`).join("\n")}\n`;
	if (d.references.length) out += `\n## References\n\n${d.references.map((r, i) => `${i + 1}. ${r.label} (${r.kind}): ${r.url}`).join("\n")}\n`;
	return out;
}

mkdirSync(join(root, "docs-md"), { recursive: true });
for (const d of docs) writeFileSync(join(root, path(d)), md(d));

const jobTable = `| Job | Use | How | Not this |\n|---|---|---|---|\n${jobs
	.map((j) => `| ${j.job} | **${name(j.use)}**${byId[j.use]?.kind === "component" && !built.has(j.use) ? " (planned)" : ""} | ${j.how ?? ""} | ${(j.notThis ?? []).map(name).join(", ")} |`)
	.join("\n")}`;

const agents = `# TwoUX: rules for AI coding agents

<!-- Generated by scripts/build-llm.mjs from packages/ui/registry/jobs.json and apps/docs/src/content. Do not edit by hand. -->

TwoUX is an engineering-first, compact, keyboard-first design system for complex, data-intensive B2B applications (SaaS platforms, BI tools, fintech consoles, CRMs, ERPs): information-dense interfaces, complex data tables, advanced visualisations, drill-down workflows and command-centre dashboards, in light and dark. This file is TwoUX AI Knowledge: it tells you which component and pattern fits each job and why, so you never have to guess or invent UX. Every component, token and pattern is grounded in WCAG 2.2, WAI-ARIA and the design systems of major SaaS products. Its first rule is consistency: the same job always uses the same component, the same tokens and the same behaviour. Follow these rules for every UI change, without exception. Never invent a rule, component or source that isn't in these files.

## Before writing any UI

${rules.before.map((r, i) => `${i + 1}. ${r.rule}`).join("\n")}

Rules marked **TwoUX only** are about the @twoux/ui package, its tokens and its theme. Every other rule is a principle: it also holds in an app not built with TwoUX, where the component it names is the TwoUX way of meeting it.

${rules.groups.map((g) => `## ${g.title}\n\n${g.rules.map((r) => `- ${r.scope === "twoux" ? "**TwoUX only.** " : ""}${r.rule}${r.use ? ` ${r.use.map(([l, v]) => `${l}: ${v.map((x) => "`" + x.split(" · ")[0] + "`" + (x.includes(" · ") ? ` (${x.split(" · ")[1]})` : "")).join(", ")}.`).join(" ")}` : ""} Why: ${r.why}`).join("\n")}`).join("\n\n")}

## Which component for which job

${jobTable}

## Patterns: how whole flows work

Read the pattern page before building any of these flows, and follow its steps in order.

${docs.filter((d) => d.kind === "pattern").map((d) => `- **${d.name}** (\`docs-md/${d.id}.md\`): ${d.summary}`).join("\n")}

## Tasks

These are the things you'll be asked to do. Claude Code has them as skills (/twoux-build, /twoux-design, /twoux-write, /twoux-audit); in other tools, follow the steps here.

- **Build** a page, feature or interaction: restate the request as jobs; find the pattern, then the component for each job (job table above); read each page (When not to use, Behaviour, Accessibility, Keyboard, API); plan regions, states (loading, empty, no results, error, disabled or read-only) and shortcuts; write the copy from \`docs-md/writing.md\` and \`docs-md/voice-and-tone.md\`; build with \`@twoux/ui\` only; then lay out and finish it as good UI (/twoux-design): reading order from the job, hierarchy from TwoUX type, spacing and elevation, no lazy defaults (nested cards, card grids as structure, eyebrow labels, decoration), rendered and checked at 1280, 768 and 320px in light and dark; run \`npx twoux check\`.
- **Audit** existing UI: run \`npx twoux check\`; for each region check the job, the pattern steps, the states, actions (one primary, Undo vs confirm), content against writing and voice-and-tone, AI rules and WCAG 2.2 AA; report by severity (blocks people, drift, polish) with the TwoUX page behind each fix.
- **Improve** (audit, then fix): fix in app code with TwoUX components and props, never by editing TwoUX; re-run the check.
- **Audit an app not built with TwoUX** (\`twoux init --principles\`): apply only rules not marked TwoUX only, fix with the app's own components, tokens and brand, change behaviour, structure and words but not the look of anything you rebuild, never import TwoUX components piecemeal; run \`npx twoux check --principles\`, type-check and render each changed screen before reporting.
- **Migrate** an app onto TwoUX: follow \`docs-md/migrating.md\` in order (platform, init, theme, token owners, raw colours, adapters, codemod, screen by screen, CI); propose each step and apply only what the team approves.
- **Missing something?** Use the closest existing component and ask for the addition; don't build a local one-off.

## Files

- \`llms.txt\`: index of every page.
- \`llms-full.txt\`: every page in one file.
- \`docs-md/<id>.md\`: one page per foundation, component and pattern, with guidance and real example code.
- \`packages/ui/src/styles/twoux.css\`: all tokens (installed: \`node_modules/@twoux/ui/src/styles/twoux.css\`).
- \`twoux.theme.json\`: the one place to change brand colour, corners and font (TwoUX repo: \`packages/ui/theme.json\`).
- \`npx twoux find "<job>"\` and \`npx twoux docs <id>\`: the job table and any page from the terminal. The same lookups are MCP tools (\`find_component\`, \`get_doc\`, \`list_docs\`, \`get_rules\`, \`check\`) when the \`twoux\` MCP server is connected.
`;
writeFileSync(join(root, "AGENTS.md"), agents);
writeFileSync(join(root, "CLAUDE.md"), "@AGENTS.md\n");

const section = (kind, title) =>
	`## ${title}\n\n${docs
		.filter((d) => d.kind === kind)
		.map((d) => `- [${d.name}](${path(d)}): ${d.summary}${kind === "component" && !built.has(d.id) ? " (planned)" : ""}`)
		.join("\n")}`;
writeFileSync(
	join(root, "llms.txt"),
	`# TwoUX\n\n> Engineering-first design system for complex, data-intensive B2B applications built with AI coding agents: data tables, visualisations, drill-down workflows and command-centre dashboards. TwoUX AI Knowledge: which component and pattern fits each job, and why. Same job, same component, same tokens, same behaviour. Read AGENTS.md first.\n\n- [Rules for AI coding agents](AGENTS.md)\n- [Tokens](packages/ui/src/styles/twoux.css)\n- [Job to component registry](packages/ui/registry/jobs.json)\n\n${section("foundation", "Foundation")}\n\n${section("component", "Components")}\n\n${section("pattern", "Patterns")}\n`,
);
writeFileSync(join(root, "llms-full.txt"), docs.map(md).join("\n\n---\n\n"));
// Serve the same files from the docs site, so a person or an agent can open them at /AGENTS.md, /llms.txt …
const pub = join(root, "apps/docs/public");
mkdirSync(pub, { recursive: true });
for (const f of ["AGENTS.md", "llms.txt", "llms-full.txt"]) cpSync(join(root, f), join(pub, f));
rmSync(join(pub, "docs-md"), { recursive: true, force: true });
cpSync(join(root, "docs-md"), join(pub, "docs-md"), { recursive: true });
// Ship the same knowledge inside the package, so any project that installs @twoux/ui has it at node_modules/@twoux/ui/agent/
const agentDir = join(root, "packages/ui/agent");
mkdirSync(agentDir, { recursive: true });
for (const f of ["AGENTS.md", "llms.txt", "llms-full.txt"]) cpSync(join(root, f), join(agentDir, f));
rmSync(join(agentDir, "docs-md"), { recursive: true, force: true });
cpSync(join(root, "docs-md"), join(agentDir, "docs-md"), { recursive: true });

console.log(`Wrote AGENTS.md, CLAUDE.md, llms.txt, llms-full.txt and ${docs.length} pages in docs-md/ (${built.size} components built).`);
